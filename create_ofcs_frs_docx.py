#!/usr/bin/env python3
"""Generate OFCS Functional Requirements Specification as a Word document."""

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor


def set_run_font(run, size=11, bold=False, color=None):
    run.font.name = "Calibri"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    run.font.size = Pt(size)
    run.bold = bold
    if color is not None:
        run.font.color.rgb = color


def add_heading_styled(doc, text, level):
    heading = doc.add_heading(text, level=level)
    for run in heading.runs:
        run.font.name = "Calibri"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    return heading


def add_para(doc, text, bold=False, size=11, space_after=6):
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_font(run, size=size, bold=bold)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(0)
    return p


def add_bullet(doc, text, bold_prefix=None):
    p = doc.add_paragraph(style="List Bullet")
    if bold_prefix:
        run_b = p.add_run(bold_prefix)
        set_run_font(run_b, bold=True)
        run = p.add_run(text)
        set_run_font(run)
    else:
        run = p.add_run(text)
        set_run_font(run)
    p.paragraph_format.space_after = Pt(4)
    return p


def add_numbered(doc, text):
    p = doc.add_paragraph(style="List Number")
    run = p.add_run(text)
    set_run_font(run)
    p.paragraph_format.space_after = Pt(4)
    return p


def main():
    doc = Document()

    # Page margins
    for section in doc.sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1)
        section.right_margin = Inches(1)

    # Title
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run("Functional Requirements Specification (FRS)")
    set_run_font(run, size=22, bold=True, color=RGBColor(0x1F, 0x4E, 0x79))
    title.paragraph_format.space_after = Pt(6)

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run("Offline Charging System (OFCS)")
    set_run_font(run, size=18, bold=True, color=RGBColor(0x2E, 0x75, 0xB6))
    subtitle.paragraph_format.space_after = Pt(18)

    # 1. Purpose
    add_heading_styled(doc, "1. Purpose", level=1)
    add_para(
        doc,
        "Enhance the existing Billing System, which currently supports Orders, "
        "Products, Pricing, and Billing Models, by introducing an Offline Charging "
        "System (OFCS) to collect, process, rate, and bill subscriber usage.",
    )

    # 2. Functional Requirements
    add_heading_styled(doc, "2. Functional Requirements", level=1)

    # 2.1 CDF
    add_heading_styled(doc, "2.1 Charging Data Function (CDF)", level=2)
    add_para(
        doc,
        "The Charging Data Function (CDF) collects usage records generated by network elements.",
    )
    add_para(doc, "Requirements", bold=True, space_after=4)

    add_bullet(
        doc,
        " The system shall receive CDRs from network nodes through supported network "
        "interfaces or file-based collection.",
        bold_prefix="FR-CDF-001:",
    )
    add_bullet(
        doc,
        " The system shall validate incoming files before processing.",
        bold_prefix="FR-CDF-002:",
    )
    add_bullet(
        doc,
        " Successfully received files shall be archived, while invalid files shall be "
        "moved to an error location.",
        bold_prefix="FR-CDF-003:",
    )
    add_bullet(
        doc,
        " The system shall log all received files and collection activities.",
        bold_prefix="FR-CDF-004:",
    )

    # 2.2 CGF
    add_heading_styled(doc, "2.2 Charging Gateway Function (CGF)", level=2)
    add_para(
        doc,
        "The Charging Gateway Function (CGF) retrieves, validates, normalizes, and "
        "stores CDRs for charging.",
    )
    add_para(doc, "Requirements", bold=True, space_after=4)

    add_bullet(
        doc,
        " The system shall retrieve CDR files from a configured server location on a "
        "configurable schedule (default every 15 minutes).",
        bold_prefix="FR-CGF-001:",
    )
    add_bullet(
        doc,
        " The system shall parse and normalize all CDRs into the internal data model.",
        bold_prefix="FR-CGF-002:",
    )
    add_bullet(
        doc,
        " The system shall validate mandatory fields including SUPI, timestamp, "
        "session duration, service type, and usage volume.",
        bold_prefix="FR-CGF-003:",
    )
    add_bullet(
        doc,
        " The system shall detect duplicate CDRs using SUPI, timestamp, and session duration.",
        bold_prefix="FR-CGF-004:",
    )
    add_bullet(
        doc,
        " Duplicate CDRs shall be rejected and logged.",
        bold_prefix="FR-CGF-005:",
    )
    add_bullet(
        doc,
        " Valid CDRs shall be stored in the charging database for charging processing.",
        bold_prefix="FR-CGF-006:",
    )

    # 2.3 CHF
    add_heading_styled(doc, "2.3 Charging Function (CHF)", level=2)
    add_para(
        doc,
        "The Charging Function (CHF) is responsible for processing validated usage "
        "records, applying charging rules, calculating usage charges, and providing "
        "rated usage information to the Billing Engine.",
    )
    add_para(doc, "Requirements", bold=True, space_after=4)

    add_bullet(
        doc,
        " The system shall process validated CDRs received from the CGF.",
        bold_prefix="FR-CHF-001:",
    )
    add_bullet(
        doc,
        " The system shall identify the customer's subscribed product, service, and "
        "applicable price plan.",
        bold_prefix="FR-CHF-002:",
    )
    add_bullet(
        doc,
        " The system shall calculate charges based on service type, usage volume, "
        "duration, event count, and configured charging rules.",
        bold_prefix="FR-CHF-003:",
    )
    add_bullet(
        doc,
        " The system shall validate and consume any included free quota before applying "
        "billable charges.",
        bold_prefix="FR-CHF-004:",
    )
    add_bullet(
        doc,
        " The system shall apply configured discounts, promotions, and pricing "
        "adjustments before calculating the final charge.",
        bold_prefix="FR-CHF-005:",
    )
    add_bullet(
        doc,
        " The system shall support time-based, volume-based, event-based, and "
        "session-based charging units.",
        bold_prefix="FR-CHF-006:",
    )
    add_bullet(
        doc,
        " The system shall generate rated usage records containing the calculated "
        "charges and charging details.",
        bold_prefix="FR-CHF-007:",
    )
    add_bullet(
        doc,
        " The system shall provide rated usage records to the Enterprise Billing "
        "Engine for invoice generation.",
        bold_prefix="FR-CHF-008:",
    )

    # 2.4 EBU
    add_heading_styled(doc, "2.4 Enterprise Billing Engine (EBU)", level=2)
    add_para(
        doc,
        "The Enterprise Billing Engine (EBU) accumulates rated usage records, manages "
        "billing cycles, and generates customer invoices according to the customer's "
        "billing model.",
    )

    add_heading_styled(doc, "Postpaid Billing (In Arrears)", level=3)
    add_bullet(
        doc,
        " The system shall accumulate rated usage records throughout the billing cycle.",
        bold_prefix="FR-EBU-001:",
    )
    add_bullet(
        doc,
        " The system shall apply recurring charges according to the customer's subscribed product.",
        bold_prefix="FR-EBU-002:",
    )
    add_bullet(
        doc,
        " The system shall calculate charges for usage exceeding the included quota.",
        bold_prefix="FR-EBU-003:",
    )
    add_bullet(
        doc,
        " The system shall generate invoices at the end of the billing cycle.",
        bold_prefix="FR-EBU-004:",
    )
    add_bullet(
        doc,
        " The invoice shall include recurring charges, usage charges, discounts, taxes "
        "(if applicable), and the total amount due.",
        bold_prefix="FR-EBU-005:",
    )

    add_heading_styled(doc, "Advance Billing", level=3)
    add_bullet(
        doc,
        " The system shall generate recurring invoices at the beginning of the billing cycle.",
        bold_prefix="FR-EBU-006:",
    )
    add_bullet(
        doc,
        " Included quotas shall become available immediately after billing.",
        bold_prefix="FR-EBU-007:",
    )
    add_bullet(
        doc,
        " Usage exceeding the included quota shall be accumulated during the billing cycle.",
        bold_prefix="FR-EBU-008:",
    )
    add_bullet(
        doc,
        " Accumulated overage charges shall be included in the next billing cycle invoice.",
        bold_prefix="FR-EBU-009:",
    )

    # 2.5 Reporting
    add_heading_styled(doc, "2.5 Reporting", level=2)
    add_para(doc, "Requirements", bold=True, space_after=4)

    add_bullet(
        doc,
        " The system shall provide reports for normalized and rated CDRs.",
        bold_prefix="FR-RPT-001:",
    )
    add_bullet(
        doc,
        " The system shall provide customer usage, charging, and billing statistics.",
        bold_prefix="FR-RPT-002:",
    )
    add_bullet(
        doc,
        " Reports shall support filtering by customer, SUPI, product, service, billing "
        "cycle, usage type, and date range.",
        bold_prefix="FR-RPT-003:",
    )
    add_bullet(
        doc,
        " Reports shall include total usage, consumed free quota, billable usage, "
        "applied discounts, and charged amounts.",
        bold_prefix="FR-RPT-004:",
    )
    add_bullet(
        doc,
        " Reports shall be exportable in CSV, Excel, and PDF formats.",
        bold_prefix="FR-RPT-005:",
    )

    # 2.6 Logging
    add_heading_styled(doc, "2.6 Logging and Audit", level=2)
    add_para(doc, "Requirements", bold=True, space_after=4)

    add_bullet(
        doc,
        " The system shall log every processing stage, including file collection, "
        "validation, duplicate detection, charging, billing, and invoice generation.",
        bold_prefix="FR-LOG-001:",
    )
    add_bullet(
        doc,
        " Audit logs shall be retained according to the configured retention policy.",
        bold_prefix="FR-LOG-002:",
    )

    # 3. Business Rules
    add_heading_styled(doc, "3. Business Rules", level=1)
    add_bullet(doc, "Only validated CDRs shall be processed for charging.")
    add_bullet(doc, "A CDR shall not be processed more than once.")
    add_bullet(
        doc,
        "Duplicate detection shall use SUPI, timestamp, and session duration.",
    )
    add_bullet(doc, "Free quota shall always be consumed before billable usage.")
    add_bullet(doc, "Discounts shall be applied before invoice generation.")
    add_bullet(
        doc,
        "Postpaid customers shall be billed at the end of the billing cycle.",
    )
    add_bullet(
        doc,
        "Advance-billed customers shall pay recurring charges at the start of the "
        "cycle, while overage charges shall be included in the following invoice.",
    )
    add_bullet(
        doc,
        "All charging and billing activities shall be fully auditable.",
    )

    # 4. Process Flow
    add_heading_styled(doc, "4. Process Flow", level=1)
    add_numbered(doc, "Network nodes generate usage records (CDRs).")
    add_numbered(
        doc,
        "CDF collects CDRs through network interfaces or files.",
    )
    add_numbered(
        doc,
        "CGF retrieves, validates, normalizes, and stores CDRs while removing duplicates.",
    )
    add_numbered(
        doc,
        "CHF processes validated CDRs, applies charging rules, calculates usage "
        "charges, and generates rated usage records.",
    )
    add_numbered(
        doc,
        "EBU receives rated usage records and accumulates charges according to the "
        "customer's billing model.",
    )
    add_numbered(
        doc,
        "EBU generates invoices according to postpaid or advance billing rules.",
    )
    add_numbered(
        doc,
        "Reports, statistics, and audit logs are generated for operational monitoring "
        "and customer reporting.",
    )

    output_path = "/workspace/OFCS_Functional_Requirements_Specification.docx"
    doc.save(output_path)
    print(f"Created: {output_path}")


if __name__ == "__main__":
    main()
